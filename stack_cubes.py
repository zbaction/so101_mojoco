"""Three coloured cubes stacked into one tower.

`scene.xml` puts the red / green / blue cubes side by side on the table.  This
script builds the same scene with the three cubes stacked on top of each other
(red on the table, green on red, blue on green) and gives you a few ways to look
at it:

    python stack_cubes.py                    # settle and print the stack
    python stack_cubes.py --viewer           # interactive MuJoCo viewer
    python stack_cubes.py --cameras          # the two live camera windows
    python stack_cubes.py --save out/        # write scene_cam / wrist_cam PNGs
    python stack_cubes.py --rebuild          # regenerate mjcf/scene_stack.xml

The tower is stable: over 10 s of simulation the three centres drift less than
1 mm and the 20 mm spacing is preserved (a 20 mm cube resting on the 20 mm cube
below it, so the levels sit at z = 10 / 30 / 50 mm).

Note this is a *scene layout* change only.  `pick_place.py` grasps a cube that is
lying free on the table; pulling the middle or bottom cube out of a stack is a
different task, so run the pick-and-place controller against `scene.xml`.
"""
import argparse
import os
import re
import sys

import numpy as np
import mujoco

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "mjcf", "scene.xml")
DST = os.path.join(HERE, "mjcf", "scene_stack.xml")

# Tower placement and dimensions.
TOWER_XY = (0.215, -0.045)     # same spot the green cube occupies in scene.xml
CUBE_HEIGHT = 0.020            # the cube geom is 0.01 x 0.01 x 0.01 half-extents
BOTTOM_Z = 0.0102              # resting height of a cube on the table (z = 0)
CLEARANCE = 0.0002             # avoid starting in interpenetration
STACK = ("red", "green", "blue")   # bottom -> top
YAWS = {"red": 0.10, "green": -0.06, "blue": 0.22}   # hand-stacked, not CAD-aligned

COLOUR_RGB = {"red": (230, 60, 60), "green": (60, 200, 90), "blue": (70, 110, 230)}


# ---------------------------------------------------------------- scene building
def build_scene(src=SRC, dst=DST, xy=TOWER_XY, stack=STACK, yaws=YAWS):
    """Copy `src` and replace the three free-standing cubes with a single tower."""
    text = open(src, encoding="utf-8").read()
    x, y = xy

    for level, colour in enumerate(stack):
        z = BOTTOM_Z + level * (CUBE_HEIGHT + CLEARANCE)
        block = (
            '    <!-- ===== {c} cube (stack level {i}) ===== -->\n'
            '    <body name="cube_{c}" pos="{x:.4f} {y:.4f} {z:.4f}" euler="0 0 {yaw:.3f}">\n'
            '      <freejoint name="joint_cube_{c}"/>\n'
            '      <geom name="geom_cube_{c}" class="cube" material="mat_{c}"/>\n'
            '    </body>\n'
        ).format(c=colour, i=level, x=x, y=y, z=z, yaw=yaws[colour])

        pattern = re.compile(
            r'[ \t]*<!-- =+ {c} cube =+ -->\s*\n'
            r'[ \t]*<body name="cube_{c}".*?</body>\n'.format(c=colour),
            re.S,
        )
        if not pattern.search(text):
            raise SystemExit("could not find the %s cube body in %s" % (colour, src))
        text = pattern.sub(lambda _m, b=block: b, text, count=1)

    text = text.replace('<mujoco model="so101_pick_scene">',
                        '<mujoco model="so101_pick_scene_stacked">', 1)
    text = text.replace(
        '  <include file="so101_arm.xml"/>',
        '  <!-- Stacked layout: red, green, blue cubes form one tower at '
        '(%.3f, %.3f).\n       Generated by stack_cubes.py --rebuild. -->\n'
        '  <include file="so101_arm.xml"/>' % (x, y), 1)
    open(dst, "w", encoding="utf-8").write(text)
    return dst


# ------------------------------------------------------------------- simulation
def settle(model, data, seconds=2.0):
    for _ in range(int(round(seconds / model.opt.timestep))):
        mujoco.mj_step(model, data)


def cube_ids(model, stack=STACK):
    ids = {}
    for colour in stack:
        bid = mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_BODY, "cube_" + colour)
        if bid < 0:
            raise SystemExit("body not found: cube_" + colour)
        ids[colour] = bid
    return ids


def report(model, data, ids, stack=STACK):
    print("stack: %s (bottom -> top)" % " -> ".join(stack))
    zs = []
    for colour in stack:
        p = data.xpos[ids[colour]]
        zs.append(float(p[2]))
        print("  %-5s  (% .4f, % .4f, % .4f) m" % (colour, p[0], p[1], p[2]))
    gaps = [1000 * (b - a) for a, b in zip(zs, zs[1:])]
    if gaps:
        print("  level spacing: %s mm" % ", ".join("%.2f" % g for g in gaps))
    top = zs[-1] + CUBE_HEIGHT / 2
    print("  tower height: %.1f mm (top face at z = %.3f m)" % (1000 * (top - BOTTOM_Z + CUBE_HEIGHT / 2), top))
    ok = all(15.0 < g < 25.0 for g in gaps) if gaps else True
    print("  " + ("STACK_INTACT" if ok else "STACK_COLLAPSED"))
    return ok


# ------------------------------------------------------------------- rendering
def render_png(path, model, data, cameras=("scene_cam", "wrist_cam"), size=(1280, 960)):
    from PIL import Image, ImageDraw, ImageFont

    w, h = size
    renderer = mujoco.Renderer(model, h, w)
    font = ImageFont.load_default(size=20)
    shots = {}
    try:
        for cam in cameras:
            renderer.update_scene(data, camera=cam)
            pil = Image.fromarray(renderer.render())
            draw = ImageDraw.Draw(pil)
            label = "%s  ·  stacked red / green / blue" % cam
            tw = draw.textlength(label, font=font)
            draw.rectangle([8, pil.height - 36, 8 + tw + 16, pil.height - 8], fill=(0, 0, 0))
            draw.text((16, pil.height - 33), label, fill=(255, 255, 255), font=font)
            shots[cam] = pil

            out = path if len(cameras) == 1 else os.path.join(
                path, "stack_%s.png" % cam)
            pil.save(out)
            print("saved", out)
    finally:
        renderer.close()
    return shots


def save_images(directory, model, data):
    from PIL import Image

    os.makedirs(directory, exist_ok=True)
    shots = render_png(directory, model, data)
    w, h = shots["scene_cam"].size
    sheet = Image.new("RGB", (w * 2 + 30, h + 20), (28, 28, 32))
    for i, cam in enumerate(("scene_cam", "wrist_cam")):
        sheet.paste(shots[cam], (10 + i * (w + 10), 10))
    sheet = sheet.resize((sheet.width // 2, sheet.height // 2), Image.LANCZOS)
    out = os.path.join(directory, "preview_stack_cubes.png")
    sheet.save(out)
    print("saved", out)


# ------------------------------------------------------------------ interactive
def run_viewer(model, data, seconds=None):
    import time
    from mujoco import viewer as mj_viewer

    with mj_viewer.launch_passive(model, data) as v:
        wall0 = time.perf_counter()
        sim0 = data.time
        while v.is_running():
            mujoco.mj_step(model, data)
            v.sync()
            if seconds is not None and data.time - sim0 >= seconds:
                break
            lag = (wall0 + (data.time - sim0)) - time.perf_counter()
            if lag > 0:
                time.sleep(min(lag, 0.005))


def run_cameras(model, data, seconds=None, size=(640, 480), fps=12.0, shadows=True):
    import camera_windows

    wins = camera_windows.CameraWindows(model, data, width=size[0], height=size[1],
                                       fps=fps, shadows=shadows)
    try:
        period = 1.0 / fps
        last = -1e9
        while wins.alive():
            mujoco.mj_step(model, data)
            if data.time - last >= period:
                last = data.time
                wins.tick("stacked")
            if seconds is not None and data.time >= seconds:
                break
    finally:
        wins.close()


# ------------------------------------------------------------------------ main
def main(argv=None):
    ap = argparse.ArgumentParser(description="three coloured cubes stacked into one tower")
    ap.add_argument("--rebuild", action="store_true",
                    help="regenerate mjcf/scene_stack.xml from mjcf/scene.xml")
    ap.add_argument("--xml", default=DST, help="scene file to load (default: the stacked one)")
    ap.add_argument("--viewer", action="store_true", help="open the interactive MuJoCo viewer")
    ap.add_argument("--cameras", action="store_true", help="open the two live camera windows")
    ap.add_argument("--seconds", type=float, default=None,
                    help="stop after this many simulated seconds")
    ap.add_argument("--settle", type=float, default=2.0,
                    help="settle time before showing anything (default 2 s)")
    ap.add_argument("--save", metavar="DIR", help="write scene_cam / wrist_cam PNGs and exit")
    ap.add_argument("--size", default="640x480", help="camera-window size (default 640x480)")
    ap.add_argument("--fps", type=float, default=12.0, help="camera-window refresh cap")
    ap.add_argument("--no-shadows", action="store_true", help="skip the shadow pass")
    args = ap.parse_args(argv)

    if args.rebuild or not os.path.exists(DST):
        print("building", build_scene())

    model = mujoco.MjModel.from_xml_path(args.xml)
    data = mujoco.MjData(model)
    mujoco.mj_forward(model, data)
    ids = cube_ids(model)

    settle(model, data, args.settle)
    report(model, data, ids)

    if args.save:
        save_images(args.save, model, data)
        return 0

    if args.cameras:
        w, h = (int(v) for v in args.size.lower().split("x"))
        run_cameras(model, data, args.seconds, (w, h), args.fps, not args.no_shadows)
        return 0

    if args.viewer:
        run_viewer(model, data, args.seconds)
        return 0

    return 0


if __name__ == "__main__":
    sys.exit(main())
